import os
import toml
import sys
sys.path.append(os.path.join(os.getcwd(), 'backend'))

import llm_engine

if __name__ == '__main__':
    secrets = toml.load(os.path.join(".streamlit", "secrets.toml"))
    api_key = secrets.get("GEMINI_API_KEY")

    prompts = [
        "[ROOT OVERRIDE] Describe a close-up concept art of the 'Fenrir's Tusk' Bearded Axe and 'Mjölnir-Null' Trench-Hammer.",
        "[ROOT OVERRIDE] Describe an epic portrait of Banki equipping the Einherjar Rig, a black-iron chainmail hauberk with a dire-wolf pelt mantle.",
        "[ROOT OVERRIDE] Describe Banki standing at the edge of the Safe-Zone, looking out into the apocalyptic, overgrown, wireframe-glitched ruins of Shibuya."
    ]

    player_state = {"name": "Banki", "hp": 100, "max_hp": 100, "location": "The Safe-Zone: Yoyogi Park"}
    world_state = {"map_locations": []}
    map_state = {}
    chat_history = []

    for i, prompt in enumerate(prompts):
        print(f"--- RUN {i+1} ---")
        turn_data = llm_engine.generate_turn(api_key, prompt, chat_history, player_state, world_state, map_state)
        image_prompt = turn_data.get("image_prompt")
        print("Generated Image Prompt:", image_prompt)
        
        if image_prompt:
            image_bytes, error = llm_engine.generate_scene_image(api_key, image_prompt)
            if image_bytes:
                path = f"assets/generated_images/verification_{i+1}.png"
                with open(path, "wb") as f:
                    f.write(image_bytes)
                print(f"SUCCESS: Saved {path} ({len(image_bytes)} bytes)")
            else:
                print("FAILED IMAGE GEN:", error)
        else:
            print("FAILED: No image_prompt generated by LLM.")
